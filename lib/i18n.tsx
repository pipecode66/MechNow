const I18nContext = React.createContext<I18nContextValue | null>(null)

function format(template: string, values?: TranslationValues): string {
  if (!values) return template
  return Object.entries(values).reduce(
    (text, [key, value]) => text.replaceAll(`{${key}}`, String(value)),
    template
  )
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = React.useState<Language>("en")

  React.useEffect(() => {
    const stored = window.localStorage.getItem("mechnow-lang")
    if (stored === "en" || stored === "es") {
      const timeout = window.setTimeout(() => {
        setLangState(stored)
        document.documentElement.lang = stored
      }, 0)

      return () => window.clearTimeout(timeout)
    }

    return undefined
  }, [])

  const setLang = React.useCallback((nextLang: Language) => {
    setLangState(nextLang)
    window.localStorage.setItem("mechnow-lang", nextLang)
    document.documentElement.lang = nextLang
  }, [])

  const t = React.useCallback(
    (key: string, values?: TranslationValues) => {
      const template = dictionaries[lang][key] ?? dictionaries.en[key] ?? key
      return format(template, values)
    },
    [lang]
  )

  const value = React.useMemo(
    () => ({ lang, setLang, t }),
    [lang, setLang, t]
  )

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const context = React.useContext(I18nContext)
  if (!context) {
    throw new Error("useI18n must be used within I18nProvider")
  }
  return context
}
